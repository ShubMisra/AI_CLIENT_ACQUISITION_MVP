"""Build byte-stable fictional PDFs from the frozen source.json. No network."""
from __future__ import annotations

import argparse
import io
import json
from pathlib import Path

from pypdf import PdfWriter
from pypdf.generic import DecodedStreamObject, DictionaryObject, NameObject

HERE = Path(__file__).resolve().parent


def _pdf_literal(value: str) -> bytes:
    if not value.isascii():
        raise ValueError("Fixture PDF text must be ASCII")
    return (value.replace("\\", "\\\\").replace("(", "\\(")
            .replace(")", "\\)")).encode("ascii")


def build_pdf(pages: list[dict]) -> bytes:
    writer = PdfWriter()
    writer.add_metadata({"/Title": "FICTIONAL SYNTHETIC TEST DATA", "/Author": "Fixture generator"})
    font = writer._add_object(DictionaryObject({
        NameObject("/Type"): NameObject("/Font"),
        NameObject("/Subtype"): NameObject("/Type1"),
        NameObject("/BaseFont"): NameObject("/Helvetica"),
    }))
    for source_page in pages:
        page = writer.add_blank_page(width=612, height=792)
        page[NameObject("/Resources")] = DictionaryObject({
            NameObject("/Font"): DictionaryObject({NameObject("/F1"): font})
        })
        lines = source_page["lines"]
        if not 1 <= len(lines) <= 25:
            raise ValueError("Fixture page line count outside bounds")
        content = bytearray(b"BT /F1 11 Tf 45 745 Td 22 TL\n")
        for line in lines:
            content.extend(b"(" + _pdf_literal(line) + b") Tj T*\n")
        content.extend(b"ET\n")
        if any(line.startswith("TABLE:") for line in lines):
            # Visible border and row rules around the three printed table rows.
            content.extend(b"44 646 520 70 re S\n44 669 m 564 669 l S\n44 691 m 564 691 l S\n")
        stream = DecodedStreamObject()
        stream.set_data(bytes(content))
        page[NameObject("/Contents")] = writer._add_object(stream)
    output = io.BytesIO()
    writer.write(output)
    return output.getvalue()


def generate(*, check: bool = False) -> dict[str, bool]:
    manifest = json.loads((HERE / "source.json").read_text(encoding="utf-8"))
    if manifest.get("synthetic_test_data_only") is not True:
        raise ValueError("Source is not explicitly synthetic")
    results = {}
    for document in manifest["documents"]:
        filename = document["filename"]
        if filename not in {"faq.pdf", "guide.pdf", "sop.pdf"}:
            raise ValueError("Unexpected fixture filename")
        output = build_pdf(document["pages"])
        target = HERE / filename
        matches = target.is_file() and target.read_bytes() == output
        results[filename] = matches
        if check and not matches:
            raise ValueError(f"Generated PDF differs from committed fixture: {filename}")
        if not check:
            target.write_bytes(output)
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes without writing")
    args = parser.parse_args()
    print(json.dumps(generate(check=args.check), sort_keys=True))
